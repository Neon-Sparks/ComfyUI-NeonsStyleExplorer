"""Phrase -> booru tag mapping used by the import/draft tooling.

Two jobs:

1. ``tags_for_text`` derives booru tags for an existing catalog entry from its
   name / natural-language clause. Rules are ordered keyword -> tags pairs.
2. ``normalise_tags`` cleans a raw tag list (e.g. the tag column of the idea
   tables, which contains a lot of snake-cased English that is not a real tag)
   against ``data/danbooru_tags.txt``, applying aliases and dropping the rest.

Nothing here touches the runtime; the node only ever reads the built JSON.
"""

import os
