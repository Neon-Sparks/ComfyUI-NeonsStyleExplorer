COMPILED = [(re.compile(pattern, re.I), tags) for pattern, tags in RULES]


def normalise_tags(raw_tags):
    """Clean a raw tag list: lowercase, alias-map, vocabulary-filter, dedupe.

    Returns ``(tags, dropped)``.
    """
    out = []
    dropped = []
    seen = set()
    for raw in raw_tags or []:
        tag = str(raw).strip().lower().replace(" ", "_")
        tag = tag.strip(",;.")
        if not tag:
            continue
        tag = ALIASES.get(tag, tag)
        if tag not in VOCAB:
            dropped.append(raw)
            continue
        if tag in seen:
            continue
        seen.add(tag)
        out.append(tag)
    return out, dropped


def tags_for_text(*chunks, limit=8):
    """Derive booru tags from free text (entry name + natural-language clause)."""
    text = " ".join(str(chunk or "") for chunk in chunks)
    out = []
    seen = set()
    for pattern, tags in COMPILED:
        if not pattern.search(text):
            continue
        for tag in tags:
            if tag in seen or tag not in VOCAB:
                continue
            seen.add(tag)
            out.append(tag)
    return out[:limit]


