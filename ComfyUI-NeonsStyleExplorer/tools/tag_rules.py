def negative_tags_for(text, limit=6):
    """Map a comma-separated natural-language negative into booru tags."""
    out = []
    seen = set()
    for chunk in str(text or "").split(","):
        key = re.sub(r"\s+", " ", chunk.strip().lower())
        if not key:
            continue
        tag = NEGATIVE_TAG_MAP.get(key)
        if not tag:
            for phrase, mapped in NEGATIVE_TAG_MAP.items():
                if phrase in key:
                    tag = mapped
                    break
        if not tag or tag in seen or tag not in VOCAB:
            continue
        seen.add(tag)
        out.append(tag)
    return out[:limit]
